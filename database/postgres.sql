CREATE SCHEMA IF NOT EXISTS ewu_lab;
REVOKE ALL ON SCHEMA ewu_lab FROM PUBLIC, anon, authenticated;
CREATE TABLE IF NOT EXISTS ewu_lab.equipment (
    id text PRIMARY KEY,
    name text NOT NULL,
    category text NOT NULL,
    quantity integer NOT NULL CHECK (quantity >= 0)
);
CREATE TABLE IF NOT EXISTS ewu_lab.reservations (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id text NOT NULL CHECK (student_id ~ '^[A-Za-z0-9][A-Za-z0-9-]{0,39}$'),
    equipment_id text NOT NULL REFERENCES ewu_lab.equipment(id),
    reservation_date text NOT NULL CHECK (reservation_date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
    start_time text NOT NULL CHECK (start_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    end_time text NOT NULL CHECK (end_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' AND end_time > start_time),
    quantity integer NOT NULL CHECK (quantity > 0),
    status text NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected')),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS reservation_slots ON ewu_lab.reservations(equipment_id, reservation_date, status, start_time, end_time);
CREATE INDEX IF NOT EXISTS reservation_student_slots ON ewu_lab.reservations(lower(student_id), reservation_date, start_time, end_time) WHERE status IN ('Pending','Approved');
ALTER TABLE ewu_lab.equipment ENABLE ROW LEVEL SECURITY;
ALTER TABLE ewu_lab.reservations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA ewu_lab FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA ewu_lab FROM PUBLIC, anon, authenticated;
